# Documentation only: derive the article-asset index from existing registries.
wam_write_output_index <- function(root = getwd()) {
    root <- normalizePath(root, winslash = "/", mustWork = TRUE)
    settings <- file.path(root, "code", "settings")
    figures <- read.csv(file.path(settings, "figures.csv"), colClasses = "character")
    tables <- read.csv(file.path(settings, "tables.csv"), colClasses = "character")
    prefix_stage <- c(static = "static", dynamic_native = "dynamic",
        dynamic_processing = "dynamic", secondary_native = "dynamic",
        features = "features", diagnostics = "diagnostics",
        threshold_transfer = "threshold_transfer", frequency = "frequency",
        activation = "activation", configuration = "sensitivity",
        timing_sensitivity = "sensitivity", hardware = "export")
    stage <- function(source) {
        value <- unname(prefix_stage[sub("/.*", "", source)])
        if (anyNA(value)) stop("Unmapped output prefix; update the documentation stage map.")
        value[startsWith(source, "features/tables/") |
              source == "timing_sensitivity/summary.csv"] <- "export"
        value
    }
    entries <- list.files(file.path(root, "code", "stages"), pattern = "[.]R$")
    stages <- sub("[.]R$", "", sub("^[0-9]+_", "", entries))
    link_stage <- function(value) {
        entry <- entries[match(value, stages)]
        if (anyNA(entry)) stop("Stage entry point missing for output index.")
        paste0("[`", value, "`](stages/", entry, ")")
    }
    escape <- function(x) gsub("|", "\\|", x, fixed = TRUE)
    lines <- c("# Article output index", "",
        "Generated from [figures.csv](settings/figures.csv) and [tables.csv](settings/tables.csv).",
        "Run analyses before `export`; stage prerequisites are in the [code guide](README.md#stages).",
        "The stage column identifies where each source is created. Export then writes",
        "numbered assets to `results/` and records their checksums in `results/assets.csv`.",
        "Paths below use the default output directories. Figures/tables outside these",
        "registries are not generated by this workflow.", "", "## Figures", "",
        "| Article asset | Source stage | Intermediate path | Exported path |",
        "|---|---|---|---|")
    for (i in seq_len(nrow(figures))) {
        row <- figures[i, ]
        lines <- c(lines, paste0("| Figure ", row$number, " | ", link_stage(stage(row$source)),
            " | `analysis/", row$source, "` | `results/figures/figure-", row$number, ".png` |"))
    }
    lines <- c(lines, "", "Available PDF counterparts are copied beside figure PNGs.",
        "", "## Tables", "",
        "| Article asset | Title | Source stage | Intermediate path | Exported path |",
        "|---|---|---|---|---|")
    for (i in seq_len(nrow(tables))) {
        row <- tables[i, ]
        lines <- c(lines, paste0("| Table ", row$number, " | ", escape(row$title), " | ",
            link_stage(stage(row$source)), " | `analysis/", row$source,
            "` | `results/tables/table-", row$number, ".csv` |"))
    }
    lines <- c(lines, "", "Each table CSV has a corresponding `.tex` fragment.",
        "The `export` stage also assembles feature tables, the clip preview figure",
        "and the condensed timing-sensitivity summary from completed analyses.")
    path <- file.path(root, "code", "OUTPUTS.md")
    writeLines(enc2utf8(lines), path, useBytes = TRUE)
    invisible(path)
}
